import type { Metadata } from 'next';
import type { ReactNode } from 'react';
import './globals.css';
import { Geist } from "next/font/google";
import { cn } from "@/lib/utils";

// `fallback: ['sans-serif']` adds a generic last-resort fallback so characters that Geist (latin subset)
// does not cover still render with a system font instead of broken glyphs.
const geist = Geist({ subsets: ['latin'], variable: '--font-sans', fallback: ['sans-serif'] });

export const metadata: Metadata = {
  title: 'Demo Sign-up App',
  description: 'Small demo app used as the target for Playwright tests generated by AI Auto Test.',
};

export default function RootLayout({ children }: { children: ReactNode }) {
  return (
    <html lang="en" className={cn("font-sans", geist.variable)}>
      <body>{children}</body>
    </html>
  );
}
